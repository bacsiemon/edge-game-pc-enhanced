        "mov ecx, DWORD PTR [esi+0xbc]",
        "test ecx, ecx",
        "jle cu_zero",
        "push ebx",
        "push edi",
        "mov ecx, esi",
        "call 0x405b30",
        "mov ebx, eax",
        "mov ecx, esi",
        "call 0x405b60",
        "mov edi, eax",
        "test ebx, ebx",
        "jle cu_zero_pop",
        "test edi, edi",
        "jle cu_zero_pop",
        "mov eax, DWORD PTR [esi+0xbc]",
        "cdq",
        "idiv edi",
        "test edx, edx",
        "jne cu_need",
        "mov eax, DWORD PTR [esi+0xb8]",
        "cdq",
        "idiv ebx",
        "test edx, edx",
        "je cu_zero_pop",
        "cu_need:",
        "mov eax, edi",
        "shr eax, 1",
        "add eax, DWORD PTR [esi+0xbc]",
        "cdq",
        "idiv edi",
        "mov ecx, eax",
        "cmp ecx, 1",
        "jge cu_kchk",
        "mov ecx, 1",
        "cu_kchk:",
        "mov eax, ebx",
        "imul eax, ecx",
        "cmp eax, 4096",
        "jg cu_kdec",
        "mov edx, edi",
        "imul edx, ecx",
        "cmp edx, 4096",
        "jle cu_ret",
        "cu_kdec:",
