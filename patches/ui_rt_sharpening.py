        "test eax, eax",
        "je b2d_create",
        "cmp DWORD PTR [eax+0x8], ebx",
        "jne b2d_create",
        "cmp DWORD PTR [eax+0xc], edi",
        "jne b2d_create",
        "cmp DWORD PTR [eax+0x18], 0",
        "je b2d_create",
        "mov ecx, DWORD PTR [eax+0x20]",
        "test ecx, ecx",
        "je b2d_create",
